const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {PGlite}=require('@electric-sql/pglite');
const {pgcrypto}=require('@electric-sql/pglite/contrib/pgcrypto');
const {pg_trgm}=require('@electric-sql/pglite/contrib/pg_trgm');
const A='11111111-1111-4111-8111-111111111111',B='22222222-2222-4222-8222-222222222222';
test('Postgres migrations, RLS, deduplication, scoring, retry and private import',async t=>{
 const pg=new PGlite({extensions:{pgcrypto,pg_trgm}});t.after(()=>pg.close());
 await pg.exec(`create role anon; create role authenticated;create role service_role bypassrls;
 create schema auth;create table auth.users(id uuid primary key);
 create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
 grant usage on schema auth to authenticated;grant execute on function auth.uid() to authenticated;`);
 for(const file of fs.readdirSync('supabase/migrations').sort())await pg.exec(fs.readFileSync('supabase/migrations/'+file,'utf8').replace(/^\uFEFF/,''));
 await pg.query('insert into auth.users values ($1),($2)',[A,B]);
 assert.equal((await pg.query('select listed from profiles where user_id=$1',[A])).rows[0].listed,true);
 await assert.rejects(pg.query('update profiles set listed=false where user_id=$1',[A]),/profiles_ranking_required/);
 const add=(stem)=>pg.query(`insert into questions(topic,difficulty,question,options,correct,explanation,source,status,normalized,canonical_hash,signature)values('Matemática','medio',$1,'["Dois","Três","Quatro","Cinco"]',0,'Explicação correta','ai','reviewed','','','') returning id`,[stem]);
 await add('Questão única: ação?');
 await assert.rejects(add('QUESTAO unica acao!'),/duplicate key/);
 for(let i=0;i<10;i++)await add('Quanto é a soma de números do exercício '+i+'?');
 const rpc=async(name,args)=>{const placeholders=args.map((_,i)=>'$'+(i+1)).join(',');return (await pg.query(`select ${name}(${placeholders}) result`,args)).rows[0].result;};
 const game=await rpc('start_game',[A,'Matemática','medio','estudo']);assert.equal(game.available,true);assert.equal(game.questions.length,10);assert.equal(game.questions[0].correct,undefined);
 await assert.rejects(rpc('answer_game',[B,game.id,0,0]),/Partida não encontrada/);
 await assert.rejects(rpc('answer_game',[A,game.id,2,0]),/fora de ordem/);
 for(let i=0;i<10;i++){await rpc('present_game',[A,game.id,i]);const result=await rpc('answer_game',[A,game.id,i,0]);assert.equal(result.correct,0);}
 const first=await rpc('answer_game',[A,game.id,0,3]);assert.equal(first.answer,0);
 let snap=await rpc('progress_snapshot',[A]);assert.equal(snap.stats.totalGames,1);assert.equal(snap.stats.totalXP,210);assert.equal(snap.stats.bestScore,375);assert.ok(snap.badges.includes('perfecto'));
 await rpc('import_local',[A,{stats:{totalGames:2,totalCorrect:10,totalAnswered:20,totalXP:100,bestScore:80},history:[],badges:['poliglota']}]);
 await rpc('import_local',[A,{stats:{totalGames:1000}}]);snap=await rpc('progress_snapshot',[A]);assert.equal(snap.stats.totalGames,3);assert.equal(snap.stats.totalXP,310);
 const practice='33333333-3333-4333-8333-333333333333';
 for(let i=0;i<2;i++)await rpc('save_practice',[A,practice,'Matemática','estudo',5,75,new Date().toISOString()]);
 snap=await rpc('progress_snapshot',[A]);assert.equal(snap.stats.totalGames,4);
 await pg.query('update profiles set listed=true where user_id=$1',[A]);
 const ranking=(await pg.query('select * from public_ranking(false,0)')).rows;assert.equal(Number(ranking[0].score),375);assert.equal(Number(ranking[0].games),1);assert.equal(ranking[0].email,undefined);
 await pg.exec(`set role authenticated;select set_config('request.jwt.claim.sub','${B}',false);`);
 assert.equal((await pg.query('select * from user_progress')).rows.length,0);
 await assert.rejects(pg.query('select * from questions'),/permission denied/);
 await assert.rejects(pg.query('select * from game_sessions'),/permission denied/);
 await assert.rejects(rpc('progress_snapshot',[A]),/permission denied/);
 await assert.rejects(pg.query("update profiles set listed=true"),/permission denied/);
 await pg.exec('reset role');
 assert.equal(await rpc('reserve_generation',[1]),true);assert.equal(await rpc('reserve_generation',[1]),false);
});
